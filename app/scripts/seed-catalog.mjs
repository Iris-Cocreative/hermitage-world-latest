/**
 * Turns the site's catalog (assets/data/catalog.js, read from the old
 * hermitageindy.org shop on 2026-10-23) into supabase/seed.sql: one product
 * row per item, every one a DRAFT. Nothing is on sale until the team opens
 * a product in /admin and sets it active.
 *
 * Run `npm run seed:catalog` to regenerate the SQL, then `npm run db:reset`
 * to apply it locally. The SQL upserts on slug, so it is safe to run again.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const catalogPath = resolve(here, '../../assets/data/catalog.js');
const outPath = resolve(here, '../supabase/seed.sql');

// catalog.js assigns window.HWCatalog; give it a window to write to.
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(catalogPath, 'utf8'), sandbox);
const { items, people } = sandbox.window.HWCatalog;

const KIND = { track: 'track', album: 'album', book: 'book', set: 'bundle', video: 'video', series: 'video', program: 'program', circle: 'other' };

function q(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

const rows = [];
let sort = 0;
for (const it of items) {
  // "elsewhere" items (a book the Hermitage read but does not sell) stay out of the shop.
  if (it.access === 'elsewhere') continue;
  const kind = KIND[it.kind] ?? 'other';
  const price_cents = it.access === 'price' && typeof it.price === 'number' ? Math.round(it.price * 100) : 0;
  const by = (it.by || []).map((id) => people[id]?.name ?? id);
  const meta = {
    source: 'hermitageindy.org shop, read 2026-10-23',
    catalog_id: it.id,
    catalog_kind: it.kind,
    access: it.access,
    free_draft: it.freeDraft === true,
    voice: it.voice ?? null,
    by,
    album: it.album ?? null,
    vol: it.vol ?? null,
    track: it.track ?? null,
    year: it.year ?? null,
    occasion: it.occasion ?? [],
    discs: it.discs ?? null,
    hours: it.hours ?? null,
    href: it.href ?? null,
  };
  rows.push(
    `(${q(it.id)}, ${q(kind)}, ${q(it.title)}, ${q(it.sub ?? '')}, ${q(it.blurb ?? '')}, ${price_cents}, 'usd', 'draft', ${sort++}, ${q(JSON.stringify(meta))}::jsonb)`
  );
}

const sql = `-- Generated by scripts/seed-catalog.mjs from assets/data/catalog.js. Do not edit by hand.
-- ${rows.length} products, every one a draft. Prices are the old shop's (USD); "free" follows the stated policy
-- (healing meditations free) and is marked free_draft in meta until Samuel confirms it.

insert into public.products (slug, kind, title, subtitle, description, price_cents, currency, status, sort, meta)
values
${rows.join(',\n')}
on conflict (slug) do update set
  kind = excluded.kind,
  title = excluded.title,
  subtitle = excluded.subtitle,
  description = case when public.products.description = '' then excluded.description else public.products.description end,
  price_cents = case when public.products.status = 'draft' then excluded.price_cents else public.products.price_cents end,
  sort = excluded.sort,
  meta = public.products.meta || excluded.meta;
`;

writeFileSync(outPath, sql);
console.log(`seed-catalog: ${rows.length} draft products written to ${outPath}`);
