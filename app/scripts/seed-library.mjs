/**
 * Turns the site's catalog (assets/data/catalog.js) into the Collab Library's
 * first contents: supabase/seed-library.sql. It runs after seed.sql (the
 * products), so every resource that is sold or claimed links to its product
 * by slug, and the store decides its price and whether it is on sale.
 *
 * What it writes:
 *   people     PEOPLE, as library_people
 *   topics     OCCASIONS, as the "occasion" facet
 *   resources  one per item, published, except where publishing would say
 *              something untrue (a past circle; a book we don't sell and have
 *              no link for): those are drafts for the team to finish
 *   relations  an album holds its volumes, a volume its tracks (an album
 *              with no volumes holds its tracks); rel.partOf, companion, reads, form
 *   paths      PATHS, as published collections
 *
 * Run `npm run seed:library`, then `npm run db:reset`. It upserts on slug and
 * leaves alone anything an editor has changed since (it only fills blanks).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const catalogPath = resolve(here, '../../assets/data/catalog.js');
const outPath = resolve(here, '../supabase/seed-library.sql');

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(catalogPath, 'utf8'), sandbox);
const { items: catalogItems, volumes = [], people, occasions, paths } = sandbox.window.HWCatalog;
// Each volume sits right after its album, so the editors' order keeps them together.
const items = catalogItems.flatMap((it) => [it, ...volumes.filter((v) => v.album === it.id)]);

// The catalog's kinds, as the library types the Hermitage keeps (0003_library_host.sql).
const TYPE = { track: 'meditation', album: 'album', volume: 'volume', book: 'book', set: 'set', video: 'video', series: 'series', program: 'program', circle: 'circle' };
const REL = { partOf: 'part-of', companion: 'companion', reads: 'reads', form: 'other-form' };

const q = (s) => (s === null || s === undefined ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");
const n = (v) => (typeof v === 'number' && Number.isFinite(v) ? String(Math.round(v)) : 'null');

const out = [];
out.push(`-- Generated by scripts/seed-library.mjs from assets/data/catalog.js. Do not edit by hand.
-- The Collab Library's first contents. Runs after seed.sql (the products).
`);

// people
out.push(`insert into public.library_people (slug, name, short_name, role, sort) values`);
out.push(
  Object.entries(people)
    .map(([id, p], i) => `  (${q(id)}, ${q(p.name)}, ${q(p.short ?? '')}, ${q(p.role ?? '')}, ${i})`)
    .join(',\n') +
    `\non conflict (slug) do update set name = excluded.name, short_name = excluded.short_name,
  role = case when public.library_people.role = '' then excluded.role else public.library_people.role end;\n`,
);

// topics: when or why you would reach for something
out.push(`insert into public.library_topics (slug, name, facet, sort) values`);
out.push(
  Object.entries(occasions)
    .map(([id, name], i) => `  (${q(id)}, ${q(name)}, 'occasion', ${i})`)
    .join(',\n') + `\non conflict (slug) do update set name = excluded.name;\n`,
);

// resources
const rows = [];
let sort = 0;
for (const it of items) {
  const type = TYPE[it.kind] ?? 'meditation';
  let status = 'published';
  // A volume has no product of its own yet: it is a way into its tracks.
  let product = it.access === 'elsewhere' || it.kind === 'program' || it.kind === 'circle' || it.kind === 'volume' ? null : it.id;
  let url = it.href ? '/' + it.href.replace(/^\/+/, '') : null;
  // A book the Hermitage read but does not sell, with no link to send anyone to.
  if (it.access === 'elsewhere' && !url) status = 'draft';
  // The spring 2026 circle is past: published, it would read as coming.
  if (it.kind === 'circle') status = 'draft';
  const minutes = typeof it.minutes === 'number' ? it.minutes : typeof it.hours === 'number' ? it.hours * 60 : null;
  const meta = {
    source: 'hermitageindy.org shop and Collab OS, read 2026-10-23',
    catalog_id: it.id,
    voice: it.voice ?? null,
    vol: it.vol ?? null,
    track: it.track ?? null,
    discs: it.discs ?? null,
    lessons: it.lessons ?? null,
    sessions: it.sessions ?? it.lessons ?? null,
    thick: it.thick ?? null,
    free_draft: it.freeDraft === true,
    ...(minutes && it.hours ? { minutes_about: true } : {}),
  };
  // The old shop's photo, served by the site (assets/img/shop/); the library
  // draws it where the shape takes a cover (an album's case).
  const cover = it.img ? '/assets/' + it.img : null;
  rows.push(
    `  (${q(it.id)}, ${q(type)}, ${q(it.title)}, ${q(it.sub ?? '')}, ${q(it.blurb ?? '')}, ${q(status)}, ${q(url)}, ${q(cover)}, ` +
      `${product ? `(select id from public.products where slug = ${q(product)})` : 'null'}, ${n(minutes)}, ${n(it.year)}, ${sort++}, ${q(JSON.stringify(meta))}::jsonb)`,
  );
}
out.push(`insert into public.library_resources (slug, type, title, subtitle, blurb, status, url, cover_url, product_id, minutes, year, sort, meta) values`);
out.push(
  rows.join(',\n') +
    `\non conflict (slug) do update set
  subtitle = case when public.library_resources.subtitle = '' then excluded.subtitle else public.library_resources.subtitle end,
  blurb = case when public.library_resources.blurb = '' then excluded.blurb else public.library_resources.blurb end,
  product_id = coalesce(public.library_resources.product_id, excluded.product_id),
  url = coalesce(public.library_resources.url, excluded.url),
  cover_url = coalesce(public.library_resources.cover_url, excluded.cover_url),
  minutes = coalesce(public.library_resources.minutes, excluded.minutes),
  meta = excluded.meta || public.library_resources.meta;\n`,
);

// credits
const credits = [];
for (const it of items) (it.by ?? []).forEach((pid, i) => credits.push(`  (${q(it.id)}, ${q(pid)}, ${i})`));
out.push(`insert into public.library_resource_people (resource_id, person_id, sort)
select r.id, p.id, v.sort from (values
${credits.join(',\n')}
) as v (resource, person, sort)
join public.library_resources r on r.slug = v.resource
join public.library_people p on p.slug = v.person
on conflict do nothing;\n`);

// topics of resources
const tags = [];
for (const it of items) for (const o of it.occasion ?? []) tags.push(`  (${q(it.id)}, ${q(o)})`);
out.push(`insert into public.library_resource_topics (resource_id, topic_id)
select r.id, t.id from (values
${tags.join(',\n')}
) as v (resource, topic)
join public.library_resources r on r.slug = v.resource
join public.library_topics t on t.slug = v.topic
on conflict do nothing;\n`);

// relations
const rels = [];
const ids = new Set(items.map((i) => i.id));
for (const it of items) {
  const holder = it.volume && ids.has(it.volume) ? it.volume : it.album;
  if (holder && ids.has(holder)) rels.push([it.id, holder, 'part-of']);
  for (const [key, kind] of Object.entries(REL)) for (const to of it.rel?.[key] ?? []) if (ids.has(to)) rels.push([it.id, to, kind]);
}
const uniq = [...new Map(rels.map((r) => [r.join('|'), r])).values()];
out.push(`insert into public.library_relations (from_id, to_id, kind, sort)
select a.id, b.id, v.kind, v.sort from (values
${uniq.map(([a, b, k], i) => `  (${q(a)}, ${q(b)}, ${q(k)}, ${i})`).join(',\n')}
) as v (a, b, kind, sort)
join public.library_resources a on a.slug = v.a
join public.library_resources b on b.slug = v.b
on conflict do nothing;
-- A meditation that sits in a volume no longer sits straight in the album
-- (a database seeded before volumes had it there).
delete from public.library_relations x
using public.library_resources t, public.library_resources a
where x.kind = 'part-of' and x.from_id = t.id and x.to_id = a.id and a.type = 'album'
  and exists (select 1 from public.library_relations y join public.library_resources v on v.id = y.to_id
              where y.from_id = t.id and y.kind = 'part-of' and v.type = 'volume');\n`);

// paths
out.push(`insert into public.library_collections (slug, title, blurb, by_line, time_line, status, sort) values`);
out.push(
  paths.map((p, i) => `  (${q(p.id)}, ${q(p.title)}, ${q(p.desc ?? '')}, ${q(p.by ?? '')}, ${q(p.time ?? '')}, 'published', ${i})`).join(',\n') +
    `\non conflict (slug) do nothing;\n`,
);
const stops = [];
for (const p of paths) p.stops.forEach(([rid, note], i) => stops.push(`  (${q(p.id)}, ${q(rid)}, ${i}, ${q(note)})`));
out.push(`insert into public.library_collection_items (collection_id, resource_id, sort, note)
select c.id, r.id, v.sort, v.note from (values
${stops.join(',\n')}
) as v (collection, resource, sort, note)
join public.library_collections c on c.slug = v.collection
join public.library_resources r on r.slug = v.resource
on conflict do nothing;\n`);

writeFileSync(outPath, out.join('\n'));
console.log(`seed-library: ${rows.length} resources, ${uniq.length} relations, ${paths.length} paths written to ${outPath}`);
